pub fn run() {
    // ១. ប្រកាសអថេររក្សាទុកសីតុណ្ហភាពជា Celsius
    // យើងប្រើប្រាស់ f64 (floating-point 64-bit) សម្រាប់លេខទសភាគ (មានក្បៀស)
    let celsius: f64 = 35.5;

    // ២. គណនាបម្លែងទៅជា Fahrenheit តាមរូបមន្ត៖ (C * 9/5) + 32
    // សម្គាល់៖ ដោយសារ Rust តឹងរ៉ឹងលើប្រភេទព័ត៌មាន យើងត្រូវសរសេរ .0 នៅពីក្រោយលេខទាំងអស់
    let fahrenheit: f64 = (celsius * 9.0 / 5.0) + 32.0;

    // ៣. បង្ហាញលទ្ធផលទៅកាន់អេក្រង់
    println!("=== កម្មវិធីបម្លែងសីតុណ្ហភាព ===");
    println!("សីតុណ្ហភាព Celsius គឺ៖ {}°C", celsius);
    println!("សីតុណ្ហភាព Fahrenheit គឺ៖ {}°F", fahrenheit);
}